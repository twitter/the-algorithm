package com.twitter.search.common.relevance.classifiers;

import java.io.IOEtwitterception;
import java.util.Set;

import com.google.common.base.Preconditions;

import com.twitter.common.tetwittert.transformer.RegetwitterTransformer;
import com.twitter.common.tetwittert.transformer.RtRemovalTransformer;
import com.twitter.common.tetwittert.transformer.Transformer;
import com.twitter.common.tetwittert.transformer.TransformerChain;
import com.twitter.common_internal.tetwittert.duplicate.RandomSubstringEtwittertractor;
import com.twitter.common_internal.tetwittert.duplicate.SignatureGenerator;
import com.twitter.common_internal.tetwittert.version.PenguinVersion;
import com.twitter.search.common.relevance.entities.TwitterMessage;
import com.twitter.search.common.relevance.features.TweetIntegerShingleSignature;
import com.twitter.search.common.relevance.features.TweetTetwittertFeatures;
import com.twitter.search.common.util.tetwittert.NormalizerHelper;
import com.twitter.twittertetwittert.Regetwitter;

/**
 * Given a tweet tetwittert, etwittertract useful tetwittert features.
 */
public class TweetQualityFeatureEtwittertractor {
  private static final Transformer STATUS_TEtwitterT_CLEANER =
      TransformerChain.of(
          // remove @reply as defined in twitter-tetwittert
          new RegetwitterTransformer.Builder()
              .setRegetwitterPattern(Regetwitter.VALID_REPLY)
              .setReplaceString("")
              .setTriggeringChar('@')
              .build(),
          // remove the old style retweet, eg RT: @mention or via @mention
          new RtRemovalTransformer()
      );

  // for signature generation
  private static final int MIN_NUM_FEATURES = 2;
  private final SignatureGenerator signatureGenerator = new SignatureGenerator(
      new RandomSubstringEtwittertractor(
          TweetIntegerShingleSignature.NUM_SHINGLES, // number of signatures
          MIN_NUM_FEATURES, // each signature is generated by taking this number of features/tokens
                            // from tetwittert
          false, // do not consider full tweet tetwittert as a feature
          false)); // do not do early termination

  /**
   * Given TwitterMessage, etwittertract all interesting tweet tetwittert features and store in
   * the returned TweetTetwittertFeatures object.
   *
   * @param tweet TwitterMessage to etwittertract features from
   * @throws IOEtwitterception
   */
  public void etwittertractTweetTetwittertFeatures(final TwitterMessage tweet) {
    Preconditions.checkNotNull(tweet);

    for (PenguinVersion penguinVersion : tweet.getSupportedPenguinVersions()) {
      // Get basic features.
      TweetTetwittertFeatures tetwittertFeatures = tweet.getTweetTetwittertFeatures(penguinVersion);

      etwittertractCharLength(tetwittertFeatures);

      // Signature that hashes on tetwittert with resolved urls, aggressively remove RT tags, which
      // accounts for more than 50% of neardups, also remove @mentions.
      // we use resolved urls for signature since they are what matters.
      CharSequence strippedTetwittert = tweet.getTetwittertReplacedWithResolvedURLs();
      strippedTetwittert = strippedTetwittert == null ? "" : strippedTetwittert;
      strippedTetwittert = STATUS_TEtwitterT_CLEANER.transform(strippedTetwittert);

      // Generate the signature.
      // will lower case, use penguin
      String normalizedSignatureTetwittert =
        NormalizerHelper.normalize(strippedTetwittert, tweet.getLocale(), penguinVersion);
      if (normalizedSignatureTetwittert != null && !normalizedSignatureTetwittert.isEmpty()) {
        Set<byte[]> rawSignature =
          signatureGenerator.generateSignatureByteArray(normalizedSignatureTetwittert);
        tetwittertFeatures.setSignature((new TweetIntegerShingleSignature(rawSignature)).serialize());
      }
    }
  }

  /**
   * Compute number of letters in stripped tweet tetwittert, also records unsupported char counts.
   *
   * @param tetwittertFeatures TweetTetwittertFeatures object to store letter length, unsupported chars, etc.
   */
  private static void etwittertractCharLength(final TweetTetwittertFeatures tetwittertFeatures) {
    Preconditions.checkNotNull(tetwittertFeatures);
    int length = 0;
    int caps = 0;
    String strippedTetwittert = tetwittertFeatures.getNormalizedStrippedTetwittert();
    if (strippedTetwittert != null && !strippedTetwittert.isEmpty()) {
      for (char c : strippedTetwittert.toCharArray()) {
        if (Character.isLetter(c)) {
          length++;
          if (Character.isUpperCase(c)) {
            caps++;
          }
        }
      }
    }
    tetwittertFeatures.setLength(length);
    tetwittertFeatures.setCaps(caps);
  }
}
