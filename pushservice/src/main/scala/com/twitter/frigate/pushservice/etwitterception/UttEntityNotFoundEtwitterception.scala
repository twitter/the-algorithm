package com.twitter.frigate.pushservice.etwitterception

import scala.util.control.NoStackTrace

/**
 * Throw etwitterception if UttEntity is not found where it might be a required data field
 *
 * @param message Etwitterception message
 */
class UttEntityNotFoundEtwitterception(private val message: String)
    etwittertends Etwitterception(message)
    with NoStackTrace
